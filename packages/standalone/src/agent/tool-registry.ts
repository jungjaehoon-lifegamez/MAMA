// ─── Public API ──────────────────────────────────────────────────────────────

export class ToolRegistry {
  /**
   * Get all registered tool names.
   */
  static getValidToolNames(): GatewayToolName[] {
    return [..._tools.keys()];
  }

  /**
   * Get tool metadata by name.
   */
  static getTool(name: string): ToolDefinitionMeta | undefined {
    return _tools.get(name as GatewayToolName);
  }

  /**
   * Get all tool definitions.
   */
  static getAllTools(): ToolDefinitionMeta[] {
    return [..._tools.values()];
  }

  /**
   * Get tools filtered by allowed list.
   * If allowedTools is undefined, returns all tools. An empty list returns none.
   * Supports wildcard patterns: "mama_*", "browser_*", "*"
   */
  static getFilteredTools(allowedTools?: readonly string[]): ToolDefinitionMeta[] {
    if (allowedTools === undefined || allowedTools.includes('*')) {
      return ToolRegistry.getAllTools();
    }

    return ToolRegistry.getAllTools().filter((tool) =>
      allowedTools.some((pattern) => matchToolPattern(pattern, tool.name))
    );
  }

  /** Expand optional exact/glob patterns to canonical registry names. */
  static expandToolPatterns(patterns?: readonly string[]): string[] {
    if (patterns === undefined) {
      return ToolRegistry.getValidToolNames();
    }
    if (patterns.length === 0) {
      return [];
    }
    return ToolRegistry.getAllTools()
      .filter((tool) => patterns.some((pattern) => matchToolPattern(pattern, tool.name)))
      .map((tool) => tool.name);
  }

  /**
   * Convert role-filtered registry metadata to Codex dynamic functions.
   * Argument validation remains the responsibility of GatewayToolExecutor.
   */
  static getHostToolDefinitions(options: HostToolDefinitionOptions = {}): HostToolDefinition[] {
    const { allowedTools, blockedTools, disallowedTools, viewer = false } = options;

    return ToolRegistry.getAllTools()
      .filter((tool) => {
        if (tool.name.startsWith('mcp__') || (tool.viewerOnly && !viewer)) {
          return false;
        }
        if (
          allowedTools !== undefined &&
          !allowedTools.some((pattern) => matchToolPattern(pattern, tool.name))
        ) {
          return false;
        }
        if (blockedTools?.some((pattern) => matchToolPattern(pattern, tool.name))) {
          return false;
        }
        return !disallowedTools?.some((pattern) => matchToolPattern(pattern, tool.name));
      })
      .map((tool) => ({
        type: 'function',
        name: tool.name,
        description: tool.params
          ? `${tool.description} Parameters: ${tool.params}`
          : tool.description,
        inputSchema: tool.inputSchema ?? {
          type: 'object',
          properties: {},
          additionalProperties: true,
        },
      }));
  }

  /**
   * Get tools grouped by category.
   */
  static getByCategory(): Map<ToolCategory, ToolDefinitionMeta[]> {
    const grouped = new Map<ToolCategory, ToolDefinitionMeta[]>();
    for (const tool of _tools.values()) {
      const list = grouped.get(tool.category) || [];
      list.push(tool);
      grouped.set(tool.category, list);
    }
    return grouped;
  }

  /**
   * Check if a tool name is registered.
   */
  static isRegistered(name: string): boolean {
    return _tools.has(name as GatewayToolName);
  }

  /**
   * Validate that all registered tools have handlers in an executor.
   * Returns list of tool names with missing handlers.
   */
  static validateHandlers(handlerNames: Set<string>): string[] {
    const missing: string[] = [];
    for (const name of _tools.keys()) {
      if (!handlerNames.has(name)) {
        missing.push(name);
      }
    }
    return missing;
  }

  /**
   * Generate a markdown prompt listing all tools (or filtered subset).
   */
  static generatePrompt(allowedTools?: readonly string[]): string {
    const tools = ToolRegistry.getFilteredTools(allowedTools);
    const grouped = new Map<ToolCategory, ToolDefinitionMeta[]>();
    for (const tool of tools) {
      const list = grouped.get(tool.category) || [];
      list.push(tool);
      grouped.set(tool.category, list);
    }

    const categoryLabels: Record<ToolCategory, string> = {
      memory: 'MAMA Memory',
      business_data:
        'Business Data (progressive exploration: overview -> entities -> tasks -> messages)',
      utility: 'Utility',
      os_management: 'OS Management (viewer-only)',
      os_monitoring: 'OS Monitoring & Operator Console',
      webchat: 'Webchat',
      code_act: 'Code-Act Sandbox',
      system: 'System',
    };

    const sections: string[] = ['# Gateway Tools\n'];
    for (const [category, label] of Object.entries(categoryLabels)) {
      const catTools = grouped.get(category as ToolCategory);
      if (!catTools || catTools.length === 0) continue;
      sections.push(`## ${label}\n`);
      for (const tool of catTools) {
        const paramHint = tool.params ? `(${tool.params})` : '()';
        sections.push(`- **${tool.name}**${paramHint} — ${tool.description}`);
      }
      sections.push('');
    }

    return sections.join('\n').trim();
  }

  /**
   * Generate a compact fallback prompt (for when gateway-tools.md is not available).
   */
  static generateFallbackPrompt(allowedTools?: readonly string[]): string {
    const tools = ToolRegistry.getFilteredTools(allowedTools);
    const grouped = new Map<ToolCategory, string[]>();
    for (const tool of tools) {
      const list = grouped.get(tool.category) || [];
      list.push(tool.name);
      grouped.set(tool.category, list);
    }

    const parts: string[] = [];
    for (const [category, names] of grouped) {
      parts.push(`**${category}:** ${names.join(', ')}`);
    }
    return parts.join('\n');
  }

  /**
   * Total number of registered tools.
   */
  static get count(): number {
    return _tools.size;
  }
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

/**
 * Match a tool name against a minimatch glob pattern.
 */
function matchToolPattern(pattern: string, toolName: string): boolean {
  return minimatch(toolName, pattern);
}
